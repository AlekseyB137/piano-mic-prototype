/**
 * Мелодия для записи по сценарию (кнопка «Запись» в «Отладке»): обычные падающие ноты, игра не
 * ждёт. Пользователь играет то, что падает; правильный ответ известен заранее. На части шагов
 * анализатор ТАЙНО проверяет другие ноты (checkAs) — там правильный ответ «не засчитано»: так
 * проверяем ловлю ошибок (сосед, октава, гармоника, неполный аккорд), не прося играть неправильно.
 * Собрано по живым проблемам: диапазон, повторы, игра поверх держащегося баса (К Элизе), аккорды.
 */
import { autoFingering } from '../import/common';
import { midiToName } from '../audio/notes';
import type { Song, SongNote } from '../song/types';

const N = (name: string): number => {
  const m = /^([A-G])(#?)(\d)$/.exec(name)!;
  const pc = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 }[m[1] as 'C'] + (m[2] ? 1 : 0);
  return 12 * (Number(m[3]) + 1) + pc;
};

const notes: SongNote[] = [];
const checkAs: { start: number; midis: number[] }[] = [];
/** Ноты на доле start (dur в долях); secret — что тайно проверять вместо них. */
function at(start: number, names: string[], dur = 1, secret?: string[]): void {
  for (const n of names) {
    const pitch = N(n);
    notes.push({ pitch, name: midiToName(pitch), start, dur, hand: pitch < 60 ? 'L' : 'R', finger: 1 });
  }
  if (secret) checkAs.push({ start, midis: secret.map(N) });
}

// Одиночные ноты по диапазону
['C3', 'G3', 'C4', 'E4', 'A4', 'C5', 'D#5', 'E5', 'G5', 'B5'].forEach((n, i) => at(i, [n]));
// Повторы одной ноты
[10, 11, 12].forEach((b) => at(b, ['C4']));
[13, 14, 15].forEach((b) => at(b, ['E5']));
// Тайно не та нота: сосед, полтона, октава выше/ниже, гармоника (G4 = 3-я гармоника C3)
at(17, ['D4'], 1, ['C4']);
at(18, ['D#5'], 1, ['E5']);
at(19, ['C5'], 1, ['C4']);
at(20, ['C4'], 1, ['C5']);
at(21, ['C3'], 1, ['G4']);
// Бас держится, правая рука поверх (A4 и E4 — октавы над басом)
at(23, ['A3'], 4);
at(24, ['C4']);
at(25, ['E4']);
at(26, ['A4']);
at(27, ['E4'], 1, ['D4']);
at(29, ['E3'], 4);
at(30, ['E4']);
at(31, ['G#4']);
at(32, ['B4']);
// Аккорды (в т.ч. тайно неполные / минор вместо мажора / только нижняя нота октавы)
at(34, ['C4', 'E4', 'G4'], 2);
at(36, ['C4', 'E4'], 2, ['C4', 'E4', 'G4']);
at(38, ['C4', 'D#4', 'G4'], 2, ['C4', 'E4', 'G4']);
at(40, ['A3', 'A4'], 2);
at(42, ['E3', 'B4'], 2);
at(44, ['C3'], 2, ['C3', 'C4']);
// К Элизе: быстрый мотив и бас под правой рукой
['E5', 'D#5', 'E5', 'D#5', 'E5', 'B4', 'D5', 'C5'].forEach((n, i) => at(46 + i * 0.5, [n], 0.5));
at(50, ['A3', 'A4'], 2);
at(51, ['C4'], 0.5);
at(51.5, ['E4'], 0.5);
at(52, ['A4'], 1);
at(53, ['E3', 'B4'], 2);

autoFingering(notes);

export const RECORD_SONG: Song = { id: 'record-scenario', title: 'Запись для отладки', bpm: 60, notes, checkAs };
